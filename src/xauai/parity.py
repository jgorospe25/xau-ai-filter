"""Phase 2 gate: compare Python signals/indicators with the DumpSignals.mq5 CSV.

Usage:  uv run python -m xauai.parity
  1. Run Scripts/xauai/DumpSignals on any MT5 chart (writes MQL5/Files/xauai_dump_signals_h1.csv).
  2. This copies the CSV into data/mt5/, compares, and writes reports/02_parity.md.
"""

from __future__ import annotations

import shutil
from dataclasses import dataclass
from datetime import datetime
from pathlib import Path

import numpy as np
import pandas as pd

from xauai import config
from xauai.signals import compute_signals

DUMP_NAME = "xauai_dump_signals_h1.csv"
WARMUP_BARS = 1000  # indicator values compared after this many bars (EMA/RSI seed effects decay)
IND_COLS = ["ema_fast", "ema_slow", "ema_trend", "rsi", "atr"]
VALUE_TOL = 1e-6


@dataclass
class ParityResult:
    mt5_bars: int
    py_bars: int
    common_bars: int
    same_first_bar: bool
    ohlc_max_diff: float
    ind_max_diff_all: dict[str, float]  # from MIN_BARS
    ind_max_diff_warm: dict[str, float]  # from WARMUP_BARS
    mt5_signals: pd.DataFrame
    py_signals: pd.DataFrame
    only_mt5: pd.DataFrame
    only_py: pd.DataFrame

    @property
    def signals_match(self) -> bool:
        return self.only_mt5.empty and self.only_py.empty

    @property
    def values_match(self) -> bool:
        return all(v <= VALUE_TOL for v in self.ind_max_diff_warm.values())


def load_dump(path: Path) -> pd.DataFrame:
    """Read the MT5 dump; drop its last row (the forming bar, where the indicator only draws early arrows)."""
    d = pd.read_csv(path)
    d["time"] = pd.to_datetime(d["time"], unit="s")
    d["signal"] = d["buy"] - d["sell"]
    # MT5 leaves 0 in warm-up slots; Python uses NaN
    d.loc[d.index < config.RSI_PERIOD, "rsi"] = np.nan
    d.loc[d.index < config.ATR_PERIOD, "atr"] = np.nan
    return d.iloc[:-1].reset_index(drop=True)


def compare(mt5: pd.DataFrame, raw: pd.DataFrame) -> ParityResult:
    py = compute_signals(raw)
    m = mt5.merge(py, on="time", suffixes=("_mt5", "_py"), validate="one_to_one")
    pos = m.index.to_numpy()  # position in the common range == bar index when first bars match
    ohlc = max(float((m[f"{c}_mt5"] - m[f"{c}_py"]).abs().max()) for c in ("open", "high", "low", "close"))

    def max_diff(start: int) -> dict[str, float]:
        sel = m[pos >= start]
        return {c: float((sel[f"{c}_mt5"] - sel[f"{c}_py"]).abs().max()) for c in IND_COLS}

    last = m["time"].iloc[-1]
    ms = mt5.loc[(mt5["signal"] != 0) & (mt5["time"] <= last), ["time", "signal"]]
    ps = py.loc[(py["signal"] != 0) & (py["time"] <= last), ["time", "signal"]]
    both = ms.merge(ps, on=["time", "signal"], how="outer", indicator=True)
    return ParityResult(
        mt5_bars=len(mt5),
        py_bars=len(raw),
        common_bars=len(m),
        same_first_bar=bool(mt5["time"].iloc[0] == raw["time"].iloc[0]),
        ohlc_max_diff=ohlc,
        ind_max_diff_all=max_diff(config.MIN_BARS),
        ind_max_diff_warm=max_diff(WARMUP_BARS),
        mt5_signals=ms,
        py_signals=ps,
        only_mt5=both.loc[both["_merge"] == "left_only", ["time", "signal"]],
        only_py=both.loc[both["_merge"] == "right_only", ["time", "signal"]],
    )


def build_report(r: ParityResult, mt5: pd.DataFrame, raw: pd.DataFrame) -> str:
    out: list[str] = []
    w = out.append
    gate = r.signals_match and r.same_first_bar
    w(f"# 02 — Indicator & signal parity: {config.SYMBOL} {config.TIMEFRAME}\n")
    w(f"Generated by `src/xauai/parity.py` at {datetime.now():%Y-%m-%d %H:%M} (local). "
      f"MT5 side: `mql5/DumpSignals.mq5` → iCustom(`XAU_EMA_RSI_Signal`, Auto preset) + iMA/iRSI/iATR.\n")
    w(f"**Gate (signal times identical, same history start): {'PASS' if gate else 'FAIL'}**\n")
    w("## Bars\n")
    w(f"- MT5 dump (closed bars): {r.mt5_bars:,}, {mt5['time'].iloc[0]} .. {mt5['time'].iloc[-1]}")
    w(f"- Python parquet: {r.py_bars:,}, {raw['time'].iloc[0]} .. {raw['time'].iloc[-1]}")
    w(f"- Common bars: {r.common_bars:,}; same first bar: {r.same_first_bar}")
    w(f"- OHLC max abs diff: {r.ohlc_max_diff:.6g}\n")
    w("## Indicator values (max abs diff, MT5 vs Python)\n")
    w(f"| indicator | from bar {config.MIN_BARS} | from bar {WARMUP_BARS} |")
    w("|---|---|---|")
    for c in IND_COLS:
        w(f"| {c} | {r.ind_max_diff_all[c]:.3e} | {r.ind_max_diff_warm[c]:.3e} |")
    w(f"\nTolerance after warm-up: {VALUE_TOL:g} → {'OK' if r.values_match else 'EXCEEDED'}\n")
    w("## Signals\n")
    for name, s in (("MT5", r.mt5_signals), ("Python", r.py_signals)):
        w(f"- {name}: {len(s)} ({int((s['signal'] == 1).sum())} buy / {int((s['signal'] == -1).sum())} sell)")
    w(f"- Only in MT5: {len(r.only_mt5)}; only in Python: {len(r.only_py)}\n")
    if not r.signals_match:
        w("Mismatches:\n")
        mm = pd.concat([r.only_mt5.assign(side="MT5 only"), r.only_py.assign(side="Python only")]).sort_values("time")
        w("| time | signal | side |\n|---|---|---|")
        for row in mm.itertuples(index=False):
            w(f"| {row.time} | {row.signal} | {row.side} |")
        w("")
    w("Signals per year (MT5):\n")
    y = r.mt5_signals.groupby(r.mt5_signals["time"].dt.year)["signal"]
    w("| year | signals | buy | sell |\n|---|---|---|---|")
    for year, s in y:
        w(f"| {year} | {len(s)} | {int((s == 1).sum())} | {int((s == -1).sum())} |")
    return "\n".join(out) + "\n"


def main() -> None:
    src = config.MT5_FILES_DIR / DUMP_NAME
    if not src.exists():
        raise SystemExit(f"{src} not found. Run Scripts/xauai/DumpSignals on an MT5 chart first.")
    config.MT5_DIR.mkdir(parents=True, exist_ok=True)
    dst = config.MT5_DIR / DUMP_NAME
    shutil.copy2(src, dst)

    mt5 = load_dump(dst)
    raw = pd.read_parquet(config.RAW_H1_PATH)
    r = compare(mt5, raw)
    report = config.REPORTS_DIR / "02_parity.md"
    report.write_text(build_report(r, mt5, raw), encoding="utf-8")
    print(f"signals match: {r.signals_match} (MT5 {len(r.mt5_signals)}, Python {len(r.py_signals)}, "
          f"only MT5 {len(r.only_mt5)}, only Python {len(r.only_py)}); values within tol: {r.values_match}")
    print(f"Wrote {report}")


if __name__ == "__main__":
    main()
