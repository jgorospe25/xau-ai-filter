@dataclass(frozen=True)
class IctVariant:
    model: str  # "m1" | "m3" | "m5"
    entry_tf: str
    tp_mode: str
    direction: bool  # keep only signals that agree with the H4/H1 direction
    time_filter: str  # "none" | "killzone" | "owner"
    eligible: bool

    @property
    def name(self) -> str:
        return "|".join([self.model, self.entry_tf, self.tp_mode, "dir" if self.direction else "nodir", self.time_filter])

    # batch-1 helpers (null_distribution, select, ...) read these
    @property
    def setup(self) -> str:
        return self.model

    @property
    def trigger_tf(self) -> None:
        return None

    @property
    def session_exit(self) -> bool:
        return False


def ict_grid() -> list[IctVariant]:
    """144 variants in a fixed order (model, TF, TP, direction off/on, time filter); eligible = M5."""
    return [
        IctVariant(m, tf, tp, dr, tfm, tf == "M5")
        for m in MODELS
        for tf in ICT_TFS
        for tp in ICT_TPS
        for dr in (False, True)
        for tfm in TIME_MODES
    ]


_GRID_INDEX: dict[IctVariant, int] = {}


def _grid_index(v: IctVariant) -> int:
    """Position of v in ict_grid() (cached map)."""
    if not _GRID_INDEX:
        _GRID_INDEX.update({g: i for i, g in enumerate(ict_grid())})
    return _GRID_INDEX[v]


# --- signals --------------------------------------------------------------------------------------
def _boxes(inp: Inputs) -> pd.DataFrame:
    key = ("ict", "boxes")
    if key not in inp.signals:
        inp.signals[key] = asian_boxes(inp.bars["M1"])
    return inp.signals[key]


def _signals(model: str, tf: str, inp: Inputs) -> pd.DataFrame:
    key = ("ict", model, tf)
    if key not in inp.signals:
        if model == "m1":
            sig = model1(inp.bars[tf], tf, _zones(inp, tf))
        elif model == "m3":
            sig = model3(_signals("m1", tf, inp))
        elif model == "m5":
            sig = model5(inp.bars[tf], tf, _boxes(inp))
        else:
            raise ValueError(f"unknown model {model!r}")
        inp.signals[key] = sig
    return inp.signals[key]


def _dir_filtered(model: str, tf: str, inp: Inputs) -> pd.DataFrame:
    """Signals whose direction equals htf_direction at the signal bar's close (0 -> dropped)."""
    key = ("ict", model, tf, "dir")
    if key not in inp.signals:
        sig = _signals(model, tf, inp)
        if len(sig):
            at = sig["signal_time"] + TF_LEN[tf]
            sig = sig[sig["direction"].to_numpy() == htf_direction(at, inp.bars["H4"], inp.bars["H1"])]
        inp.signals[key] = sig
    return inp.signals[key]


def _live(inp: Inputs, mode: str) -> np.ndarray | None:
    """M1 bars on which a limit order may fill (None = every bar)."""
    if mode == "none":
        return None
    key = ("ict", "live", mode)
    if key not in inp.signals:
        inp.signals[key] = time_filter_mask(inp.bars["M1"]["time"], mode)
    return inp.signals[key]


def _cost_swap(inp: Inputs, total_cost: float) -> tuple[CostParams, SwapParams]:
    m1 = inp.bars["M1"]
    ref = float(m1.loc[m1["time"] <= _cut(), "close"].iloc[-1])
    cost = CostParams(spread_floor=total_cost - config.SLIPPAGE, slippage=config.SLIPPAGE, point=inp.info["point"])
    return cost, SwapParams.from_symbol_info(inp.info, reference_close=ref)


def _with_offsets(out: pd.DataFrame, sig: pd.DataFrame) -> pd.DataFrame:
    """Join signal_close / signal_atr from the signal table and add offset_atr = -d (limit - close) / ATR."""
    if out.empty:  # nothing placed: the simulator's empty frame has object dtypes, so no merge
        out = out.copy()
        out["taken"] = out["taken"].astype(bool)
        for col in ("signal_close", "signal_atr", "offset_atr"):
            out[col] = pd.Series(dtype=float)
        return out
    ref = sig[["signal_time", "direction", "signal_close", "signal_atr"]].drop_duplicates(["signal_time", "direction"])
    out = out.merge(ref, on=["signal_time", "direction"], how="left")
    out["offset_atr"] = -out["direction"] * (out["limit_price"] - out["signal_close"]) / out["signal_atr"]
    return out


def run_ict_detail(
    v: IctVariant, inp: Inputs, start: str, end: str, total_cost: float = 0.35
) -> tuple[pd.DataFrame, dict[str, int]]:
    """Trades (`taken` flag: one position / order at a time) and skipped-signal counts by reason."""
    sig = _dir_filtered(v.model, v.entry_tf, inp) if v.direction else _signals(v.model, v.entry_tf, inp)
    lo, hi = pd.Timestamp(start), pd.Timestamp(end) + _DAY  # end date inclusive through 23:59:59
    sig = sig[(sig["signal_time"] >= lo) & (sig["signal_time"] < hi)]
    m1 = inp.bars["M1"]
    cost, swap = _cost_swap(inp, total_cost)
    levels = inp.levels if v.tp_mode == "next_level" else None
    if v.model in LIMIT_MODELS:
        orders, skipped = simulate_limit_signals(
            sig, m1, cost, swap, v.tp_mode, inp.windows, levels, _live(inp, v.time_filter)
        )
        out = _with_offsets(one_order(orders), sig)
    else:
        if v.time_filter != "none":
            sig = sig[time_filter_mask(sig["entry_time"], v.time_filter)]
        trades, skipped = simulate_signals(sig, m1, cost, swap, v.tp_mode, False, inp.windows, levels)
        out = one_position(trades)
    out["variant"], out["setup"], out["entry_tf"], out["tp_mode"] = v.name, v.model, v.entry_tf, v.tp_mode
    counts = {str(k): int(n) for k, n in skipped["reason"].value_counts().items()}
    return out, counts


# --- null baselines -------------------------------------------------------------------------------
def null_cands_ict(inp: Inputs, tf: str, mode: str) -> pd.DataFrame:
    """research.null_candidates (time, session) restricted to the time filter's windows."""
    key = ("ict", tf, mode)
    if key not in inp.null_cands:
        c = null_candidates(inp, tf)
        inp.null_cands[key] = c[time_filter_mask(c["time"], mode)].reset_index(drop=True)
    return inp.null_cands[key]


def limit_null_cands(inp: Inputs, tf: str, mode: str) -> pd.DataFrame:
    """null_cands_ict plus ref_close / ref_atr: close and ATR14 of the entry-TF bar before the candidate
    (the bar that closes at the placement time). Candidates without a finite ATR are dropped."""
    key = ("ict", tf, mode, "ref")
    if key not in inp.null_cands:
        c = null_cands_ict(inp, tf, mode).copy()
        bars = inp.bars[tf]
        a = atr(*(bars[k].to_numpy(dtype=float) for k in ("high", "low", "close")), _ATR_N)
        i = np.searchsorted(bars["time"].to_numpy(), c["time"].to_numpy(), side="left") - 1
        ok = i >= 0
        j = np.where(ok, i, 0)
        c["ref_close"] = np.where(ok, bars["close"].to_numpy(dtype=float)[j], np.nan)
        c["ref_atr"] = np.where(ok, a[j], np.nan)
        inp.null_cands[key] = c[np.isfinite(c["ref_atr"].to_numpy())].reset_index(drop=True)
    return inp.null_cands[key]


def limit_null_signals(
    v: IctVariant, taken: pd.DataFrame, inp: Inputs, rng: np.random.Generator, repeats: int
) -> pd.DataFrame:
    """Random limit orders for Models 1/3, one block per run (level_kind = run index). Each taken trade gets a
    candidate time T with the same session and direction (research.null_draws), a limit at a drawn offset
    from the close of the bar before T (limit = close - d x offset_atr x ATR14), fill window T .. T + K bars,
    and a jointly drawn (SL distance, TP in R)."""
    if "offset_atr" not in taken.columns:
        raise ValueError("taken trades need offset_atr (from run_ict_detail)")
    cands = limit_null_cands(inp, v.entry_tf, v.time_filter)
    ct = cands["time"].to_numpy()
    runs: list[pd.DataFrame] = []
    for k in range(repeats):
        d = null_draws(taken, cands, rng, extra=("offset_atr",))
        t = d["entry_time"]
        pos = np.searchsorted(ct, t.to_numpy())
        rc, ra = cands["ref_close"].to_numpy()[pos], cands["ref_atr"].to_numpy()[pos]
        dirs = d["direction"].to_numpy(int)
        runs.append(
            pd.DataFrame(
                {
                    "signal_time": t, "entry_time": t, "direction": dirs, "sl": np.nan, "setup": v.model,
                    "entry_tf": v.entry_tf, "trigger_tf": None, "level_kind": str(k), "level_price": np.nan,
                    "ref_time": t, "target_ob": np.nan, "target_fvg": np.nan, "target_owner": np.nan,
                    "limit_price": rc - dirs * d["offset_atr"].to_numpy(float) * ra,
                    "order_end": t + config.FILL_BARS * TF_LEN[v.entry_tf], "signal_close": rc, "signal_atr": ra,
                    "fvg_far": np.nan, "leg_end": np.nan, "ote_overlap": False,
                    "null_sl_dist": d["sl_dist"].to_numpy(float), "null_tp_r": d["tp_r"].to_numpy(float),
                    "session": d["session"].to_numpy(),
                }
            )
        )
    cols = LIMIT_SIGNAL_COLS + ["null_sl_dist", "null_tp_r", "session"]
    return pd.concat(runs, ignore_index=True)[cols] if runs else pd.DataFrame(columns=cols)


def ict_null(
    v: IctVariant, trades: pd.DataFrame, inp: Inputs, repeats: int = config.NULL_REPEATS, seed: int = NULL_SEED,
    total_cost: float = 0.35,
) -> np.ndarray:
    """Expectancy of each random run (NaN = no trade in that run); rng seed = seed + NULL_SEED_BASE + grid index.
    Candidates are restricted to the variant's time filter. Model 5: batch-1 market-entry null. Models 1/3:
    random limit orders (limit_null_signals), the variant's live mask, one order at a time per run;
    TP = the variant's RR, else the drawn TP in R."""
    taken = trades[trades["taken"].astype(bool)].reset_index(drop=True)
    if taken.empty:
        return np.full(repeats, np.nan)
    offset = NULL_SEED_BASE + _grid_index(v)
    if v.model not in LIMIT_MODELS:
        cands = null_cands_ict(inp, v.entry_tf, v.time_filter)
        return research.null_distribution(v, trades, inp, repeats, seed, total_cost, cands=cands, seed_offset=offset)
    rng = np.random.default_rng(seed + offset)
    sig = limit_null_signals(v, taken, inp, rng, repeats)
    cost, swap = _cost_swap(inp, total_cost)
    tp = v.tp_mode if v.tp_mode.startswith("rr") else "drawn"
    orders, _ = simulate_limit_signals(sig, inp.bars["M1"], cost, swap, tp, inp.windows, None, _live(inp, v.time_filter))
    out = np.full(repeats, np.nan)
    for k, g in orders.groupby("level_kind"):
        g = one_order(g)
        r = g.loc[g["taken"], "r"]
        if len(r):
            out[int(k)] = float(r.mean())
    return out


