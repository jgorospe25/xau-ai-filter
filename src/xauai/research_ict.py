"""Variant grid, runner, null baselines and selection for the batch-2 ICT entry models (1, 3, 5).

IctVariant.name format: "<model>|<entry_tf>|<tp_mode>|<dir|nodir>|<time_filter>", e.g. "m1|M5|rr2.0|dir|killzone".

Caches live in the batch-1 `Inputs` dicts under keys that start with "ict" (no collision with batch 1):
  inp.signals[("ict", model, tf)]          raw signals (Model 3 = model3(Model 1 signals))
  inp.signals[("ict", model, tf, "dir")]   signals that agree with the H4/H1 direction
  inp.signals[("ict", "boxes")]            Asian-range boxes
  inp.signals[("ict", "live", mode)]       M1 time-filter mask (ndarray) for limit fills
  inp.null_cands[("ict", tf, mode)]        null candidates inside the time filter (+ ref close / ATR14)

Models 1/3 are limit orders (simulate_limit_signals + one_order, the time filter restricts which M1 bars
can fill); Model 5 is a market entry (simulate_signals + one_position, the time filter drops signals
whose entry_time is outside the windows).
"""

